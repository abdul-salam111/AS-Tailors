/// Returns true for files that must never appear in any barrel.
bool _isExcluded(String relativePath) {
  // Barrel files themselves
  if (relativePath.endsWith('_exports.dart')) return true;
  // App entry point
  if (relativePath == 'main.dart') return true;
  // Generated code
  if (relativePath.contains('.g.dart')) return true;
  if (relativePath.contains('.freezed.dart')) return true;
  // DI registration files — imported directly by app_dependencies.dart
  if (relativePath.startsWith('core/di/register_')) return true;
  // DI orchestrator — exported from di_exports.dart manually
  if (relativePath == 'core/di/app_dependencies.dart') return true;
  return false;
}

String _toPascalCase(String text) {
  return text.split('_').map((word) {
    if (word.isEmpty) return '';
    return word[0].toUpperCase() + word.substring(1).toLowerCase();
  }).join('');
}

String _toTitleCase(String text) {
  return text.split('_').map((word) {
    if (word.isEmpty) return '';
    return word[0].toUpperCase() + word.substring(1).toLowerCase();
  }).join(' ');
}
