import 'dart:io';
import 'package:mason/mason.dart';
import 'package:path/path.dart' as p;

// ---------------------------------------------------------------------------
// export_generator
//
// Updates per-subfolder barrel export files to match the current file system:
//
//   core/constants/const_exports.dart
//   core/di/di_exports.dart
//   core/local_storage/local_storage_exports.dart
//   core/networks/network_exports.dart
//   core/services/services_exports.dart
//   core/shared/shared_exports.dart
//   core/theme/theme_exports.dart
//   core/utils/utils_exports.dart
//   core/widgets/widgets_exports.dart
//   routes/routes_exports.dart
//   features/<n>/<n>_exports.dart
//
// Files excluded from every barrel:
//   • barrel files themselves  (*_exports.dart)
//   • generated code           (*.g.dart, *.freezed.dart)
//   • app entry point          (main.dart)
//   • DI registration files    (core/di/register_*.dart)
//   • DI orchestrator          (core/di/app_dependencies.dart)
// ---------------------------------------------------------------------------

/// Maps a core sub-folder path prefix (relative to lib/) to its barrel file
/// path (relative to project root).
const _coreSubfolderBarrels = <String, String>{
  'core/constants': 'lib/core/constants/const_exports.dart',
  'core/di': 'lib/core/di/di_exports.dart',
  'core/local_storage': 'lib/core/local_storage/local_storage_exports.dart',
  'core/networks': 'lib/core/networks/network_exports.dart',
  'core/services': 'lib/core/services/services_exports.dart',
  'core/shared': 'lib/core/shared/shared_exports.dart',
  'core/theme': 'lib/core/theme/theme_exports.dart',
  'core/utils': 'lib/core/utils/utils_exports.dart',
  'core/widgets': 'lib/core/widgets/widgets_exports.dart',
};

void run(HookContext context) async {
  final logger = context.logger;
  final progress = context.logger.progress('Scanning lib/ for Dart files');

  try {
    final libDir = Directory('lib');
    if (!libDir.existsSync()) {
      progress.fail('lib/ directory not found');
      return;
    }

    // ── 1. Collect and categorise all relevant dart files ─────────────────
    final coreSubfolderFiles = <String, List<String>>{
      for (final key in _coreSubfolderBarrels.keys) key: [],
    };
    final featureFiles = <String, List<String>>{};
    final routesFiles = <String>[];

    await for (final entity in libDir.list(recursive: true)) {
      if (entity is! File) continue;
      final raw = entity.path.replaceAll(r'\', '/');
      final rel = p.relative(raw, from: 'lib').replaceAll(r'\', '/');

      if (_isExcluded(rel)) continue;

      if (rel.startsWith('routes/')) {
        routesFiles.add(rel);
      } else if (rel.startsWith('features/')) {
        final parts = rel.split('/');
        if (parts.length >= 3) {
          final featureName = parts[1];
          featureFiles.putIfAbsent(featureName, () => []).add(rel);
        }
      } else if (rel.startsWith('core/')) {
        for (final prefix in _coreSubfolderBarrels.keys) {
          if (rel.startsWith('$prefix/')) {
            coreSubfolderFiles[prefix]!.add(rel);
            break;
          }
        }
      }
    }

    // Sort all file lists
    routesFiles.sort();
    for (final files in coreSubfolderFiles.values) {
      files.sort();
    }
    for (final files in featureFiles.values) {
      files.sort();
    }

    // ── 2. Update core sub-folder barrels ─────────────────────────────────
    for (final entry in _coreSubfolderBarrels.entries) {
      final prefix = entry.key;
      final barrelPath = entry.value;
      final folderName = prefix.split('/').last;
      _updateBarrel(
        filePath: barrelPath,
        newFiles: coreSubfolderFiles[prefix]!,
        header: '// ${_toTitleCase(folderName)} barrel — '
            'auto-generated by export_generator.\n'
            '// Add package exports manually above the file exports section.\n',
        fromDir: 'lib',
        logger: logger,
      );
    }

    // ── 3. Update routes barrel ────────────────────────────────────────────
    _updateBarrel(
      filePath: 'lib/routes/routes_exports.dart',
      newFiles: routesFiles,
      header: '// Routes barrel — auto-generated by export_generator.\n'
          '// Add package exports manually above the file exports section.\n',
      fromDir: 'lib',
      logger: logger,
    );

    // ── 4. Update per-feature barrels ─────────────────────────────────────
    for (final entry in featureFiles.entries) {
      final featureName = entry.key;
      final files = entry.value;
      final barrelPath =
          'lib/features/$featureName/${featureName}_exports.dart';
      _updateBarrel(
        filePath: barrelPath,
        newFiles: files,
        header: '// ${_toPascalCase(featureName)} feature barrel — '
            'auto-generated by export_generator.\n',
        fromDir: 'lib',
        logger: logger,
      );
    }

    progress.complete('Barrels updated');
    logger.success('export_generator finished successfully');
  } catch (e) {
    progress.fail('Error generating exports');
    logger.err(e.toString());
  }
}

// ---------------------------------------------------------------------------
// Update (or create) a barrel file with the given list of source files.
// Preserves any manually added `export 'package:...'` lines at the top.
// ---------------------------------------------------------------------------
void _updateBarrel({
  required String filePath,
  required List<String> newFiles,
  required String header,
  required String fromDir,
  required Logger logger,
}) {
  final barrelFile = File(filePath);
  final existingPackageExports = <String>[];

  if (barrelFile.existsSync()) {
    final content = barrelFile.readAsStringSync();
    for (final line in content.split('\n')) {
      final trimmed = line.trim();
      if (trimmed.startsWith("export 'package:")) {
        existingPackageExports.add(trimmed);
      }
    }

    // Check for changes
    final existingFileExports = <String>{};
    final exportPattern = RegExp(r"export '([^']+)';");
    for (final line in content.split('\n')) {
      final match = exportPattern.firstMatch(line.trim());
      if (match != null) {
        final path = match.group(1)!;
        if (!path.startsWith('package:')) existingFileExports.add(path);
      }
    }

    // Compute what the new file exports will look like (as relative paths)
    final newRelativeExports = <String>{};
    for (final file in newFiles) {
      final barrelDir =
          p.dirname(filePath.replaceAll(r'\', '/')).replaceAll(r'\', '/');
      final exportPath = p
          .relative(
            p.join(fromDir, file).replaceAll(r'\', '/'),
            from: barrelDir,
          )
          .replaceAll(r'\', '/');
      newRelativeExports.add(exportPath);
    }

    final added = newRelativeExports.difference(existingFileExports);
    final removed = existingFileExports.difference(newRelativeExports);

    if (added.isEmpty && removed.isEmpty) {
      logger.info('✓ $filePath — no changes');
      return;
    }

    if (added.isNotEmpty) {
      logger.info('  + ${added.length} file(s) added to $filePath');
    }
    if (removed.isNotEmpty) {
      logger.info('  - ${removed.length} file(s) removed from $filePath');
    }
  }

  // Rebuild the barrel
  final buffer = StringBuffer();
  buffer.write(header);

  if (existingPackageExports.isNotEmpty) {
    buffer.writeln();
    buffer.writeln('// External packages');
    for (final pkg in existingPackageExports) {
      buffer.writeln(pkg);
    }
  }

  if (newFiles.isNotEmpty) {
    buffer.writeln();
    // Group by sub-folder for readability
    String? lastPrefix;
    for (final file in newFiles) {
      final barrelDir =
          p.dirname(filePath.replaceAll(r'\', '/')).replaceAll(r'\', '/');
      final exportPath = p
          .relative(
            p.join(fromDir, file).replaceAll(r'\', '/'),
            from: barrelDir,
          )
          .replaceAll(r'\', '/');

      // Print a blank line between sub-folders
      final parts = file.split('/');
      final prefix = parts.length > 2 ? parts.sublist(0, 3).join('/') : '';
      if (lastPrefix != null && prefix != lastPrefix) {
        buffer.writeln();
      }
      lastPrefix = prefix;

      buffer.writeln("export '$exportPath';");
    }
  }

  barrelFile
    ..createSync(recursive: true)
    ..writeAsStringSync(buffer.toString());

  logger.success('✓ Updated: $filePath');
}

